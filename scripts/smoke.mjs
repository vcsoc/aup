import { _electron as electron, expect } from '@playwright/test';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { weekRange, shiftRange } from '../dist/shared/stats.js';

const home = await mkdtemp(path.join(os.tmpdir(), 'aup-smoke-'));
const args = [...(process.env.AUP_EXECUTABLE ? [] : ['.']), '--demo', '--smoke', `--user-data-dir=${home}`];
if (process.platform === 'linux' && process.env.CI) args.push('--no-sandbox');
let app;
try {
  app = await electron.launch({ args, executablePath: process.env.AUP_EXECUTABLE || undefined, timeout: 30000 });
  const page = await app.firstWindow();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await expect(page.getByRole('link', { name: 'Agent Usage Panel home' })).toBeVisible();
  expect((await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getSize()))[0]).toBe(420);
  await expect(page.locator('.page-heading, .privacy-banner')).toHaveCount(0);
  await expect(page.locator('.header-actions > button')).toHaveCount(2);
  await expect(page.locator('.header-actions > button').first()).toHaveAttribute('id', 'refresh');
  await expect(page.getByRole('button', { name: 'Refresh usage' })).toHaveAttribute('title', 'Refresh usage (R)');
  await page.evaluate(() => document.fonts.ready);
  expect(await page.evaluate(() => document.fonts.check('11px "JetBrains Mono"'))).toBe(true);
  expect(await page.evaluate(() => [...document.fonts].some(font => font.family === 'JetBrains Mono' && font.status === 'loaded'))).toBe(true);
  await expect.poll(() => page.evaluate(() => Math.abs(window.innerHeight - document.querySelector('#app').getBoundingClientRect().height))).toBeLessThanOrEqual(2);
  const fullHeight = (await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getSize()))[1];
  await expect(page.getByText('DEMO MODE', { exact: true })).toBeVisible();
  await expect(page.locator('.agent-card')).toHaveCount(6);
  await expect(page.locator('.summary-cell').first()).toContainText('Uncached today');
  await expect(page.locator('.summary-cell').first()).toContainText('cached');
  await expect(page.locator('.daily-tokens').first()).toContainText('Uncached');
  expect(await page.evaluate(() => ({ require: typeof window.require, process: typeof window.process, fs: typeof window.panel.readFile }))).toEqual({ require: 'undefined', process: 'undefined', fs: 'undefined' });
  const capabilities = await app.evaluate(({ BrowserWindow }) => {
    const prefs = BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences();
    return { sandbox: prefs.sandbox, contextIsolation: prefs.contextIsolation, nodeIntegration: prefs.nodeIntegration };
  });
  expect(capabilities).toEqual({ sandbox: true, contextIsolation: true, nodeIntegration: false });
  await page.getByRole('button', { name: 'Needs attention' }).click();
  await expect(page.locator('.agent-card')).toHaveCount(1);
  await expect(page.getByRole('heading', { name: 'Kimi Code' })).toBeVisible();
  await expect.poll(async () => (await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getSize()))[1]).toBeLessThan(fullHeight);
  await page.getByRole('button', { name: 'Running', exact: true }).click();
  await expect(page.locator('.agent-card')).toHaveCount(4);
  await page.getByRole('button', { name: /All agents/ }).click();
  await page.locator('details').first().locator('summary').click();
  await expect(page.getByText('Recorded tokens', { exact: true }).first()).toBeVisible();
  await expect(page.getByText('Processed today', { exact: true }).first()).toBeVisible();
  await expect(page.getByText('Cached input today', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.locator('select[name=theme]').selectOption('dark');
  await page.getByRole('button', { name: 'Save settings' }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  const actual = await page.evaluate(() => window.panel.settings());
  expect(actual.networkEnabled).toBe(false);
  expect(actual.startAtLogin).toBe(true); // Disabled test/demo toggle must preserve the preference.
  expect((await page.evaluate(() => window.panel.info())).startupSupported).toBe(false);
  expect(actual.theme).toBe('dark');
  // Simulate malicious imported display strings through the same snapshot API.
  await page.evaluate(async () => {
    const state = await window.panel.snapshot();
    state.agents[0].name = '<img src=x onerror="window.injected=true">';
    // Renderer consumes only host snapshots, not arbitrary page messages.
    window.postMessage(state, '*');
  });
  expect(await page.locator('img').count()).toBe(0);
  expect(await page.evaluate(() => window.injected)).toBeUndefined();
  await page.locator('details').first().locator('summary').click();
  const compactLayout = await page.locator('.agent-card').evaluateAll(cards => cards.map(card => {
    const row = card.getBoundingClientRect();
    return { left: row.left, right: row.right, top: row.top, bottom: row.bottom, height: row.height, width: row.width };
  }));
  expect(compactLayout.every((row, i) => row.height <= 100 && row.width >= 380 && (i === 0 || (row.top >= compactLayout[i - 1].bottom && row.left === compactLayout[0].left)))).toBe(true);
  await expect.poll(() => page.evaluate(() => Math.abs(window.innerHeight - document.querySelector('#app').getBoundingClientRect().height))).toBeLessThanOrEqual(2);
  expect(await page.locator('.spark').evaluateAll(charts => charts.every(chart => chart.getBoundingClientRect().width >= 70))).toBe(true);
  const metrics = await page.locator('.agent-card').first().evaluate(card => {
    const tokens = card.querySelector('.daily-tokens'), cpu = card.querySelector('.metric-cpu'), ram = card.querySelector('.metric-ram');
    return { colors: [tokens, cpu, ram].map(el => getComputedStyle(el).color), tokenLabel: getComputedStyle(tokens.querySelector('span')).color, tokenValue: getComputedStyle(tokens.querySelector('strong')).color, cpuLabel: getComputedStyle(cpu.querySelector('small')).color, tokenSize: parseFloat(getComputedStyle(tokens.querySelector('strong')).fontSize), cpuSize: parseFloat(getComputedStyle(cpu).fontSize), ramSize: parseFloat(getComputedStyle(ram).fontSize) };
  });
  expect(new Set(metrics.colors).size).toBe(3);
  expect(metrics.tokenLabel).toBe(metrics.tokenValue); expect(metrics.tokenValue).toBe(metrics.colors[0]); expect(metrics.cpuLabel).toBe(metrics.colors[1]);
  expect(metrics.tokenSize).toBeGreaterThanOrEqual(12); expect(metrics.cpuSize).toBeGreaterThanOrEqual(11); expect(metrics.ramSize).toBeGreaterThanOrEqual(11);
  await expect(page.locator('.agent-cost')).toHaveCount(6);
  expect(await page.evaluate(() => [...document.querySelectorAll('body, button, input, select, h2, p, strong')].every(el => getComputedStyle(el).fontFamily.startsWith('"JetBrains Mono"')))).toBe(true);
  await mkdir('.test-results', { recursive: true });
  await page.screenshot({ path: '.test-results/panel-dark.png', fullPage: true });
  await page.getByRole('tab', { name: 'Stats', exact: true }).click();
  const currentWeek = weekRange();
  await expect(page.locator('#stats-from')).toHaveValue(currentWeek.from); await expect(page.locator('#stats-to')).toHaveValue(currentWeek.to);
  await expect(page.locator('tbody tr')).toHaveCount(6);
  await expect(page.getByRole('button', { name: 'Update prices' })).toBeDisabled();
  await expect.poll(() => page.evaluate(() => Math.abs(window.innerHeight - document.querySelector('#app').getBoundingClientRect().height))).toBeLessThanOrEqual(2);
  await page.screenshot({ path: '.test-results/stats-providers.png', fullPage: true });
  await page.getByRole('tab', { name: 'Days', exact: true }).click();
  await expect(page.locator('caption')).toContainText('Daily provider totals');
  await expect.poll(() => page.evaluate(() => Math.abs(window.innerHeight - document.querySelector('#app').getBoundingClientRect().height))).toBeLessThanOrEqual(2);
  await page.screenshot({ path: '.test-results/stats-days.png', fullPage: true });
  await page.getByRole('button', { name: 'Previous week' }).click();
  await expect(page.locator('#stats-from')).toHaveValue(shiftRange(currentWeek, -7).from);
  await page.getByRole('button', { name: 'Next week' }).click();
  await expect(page.locator('#stats-from')).toHaveValue(currentWeek.from);
  await page.locator('#stats-from').fill(shiftRange(currentWeek, 7).from);
  await expect(page.getByRole('alert')).toContainText('End date');
  await page.locator('#stats-to').fill(shiftRange(currentWeek, 7).to);
  await expect(page.getByRole('alert')).toHaveCount(0);
  await expect(page.locator('tfoot')).toContainText('$0.00');
  await page.getByRole('button', { name: 'This week' }).click();
  await page.locator('#stats-provider').selectOption('codex');
  await expect(page.locator('tbody')).not.toContainText('Claude Code');
  await page.getByRole('tab', { name: 'Providers', exact: true }).click();
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await expect(page.locator('tbody')).toContainText('Codex');
  await page.locator('#stats-provider').selectOption('all');
  await page.getByRole('tab', { name: 'Stats', exact: true }).focus(); await page.keyboard.press('ArrowLeft');
  await expect(page.getByRole('tab', { name: 'Live', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.locator('select[name=theme]').selectOption('light');
  await page.getByRole('button', { name: 'Save settings' }).click();
  await page.screenshot({ path: '.test-results/panel-light.png', fullPage: true });
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(360, 600));
  await page.waitForFunction(() => window.innerWidth === 360);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(await page.locator('.agent-card').evaluateAll(cards => cards.every(card => card.getBoundingClientRect().right <= document.documentElement.clientWidth))).toBe(true);
  // Capture the native viewport; Chromium's full-page capture can crop a
  // scrollbar-width strip when temporarily expanding a narrow native window.
  await page.screenshot({ path: '.test-results/panel-narrow.png' });
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1000, 800));
  await page.waitForFunction(() => window.innerWidth === 1000);
  const wideRows = await page.locator('.agent-card').evaluateAll(cards => cards.map(card => ({ x: card.getBoundingClientRect().x, width: card.getBoundingClientRect().width })));
  expect(wideRows.every(row => row.x === wideRows[0].x && row.width >= 960)).toBe(true);
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(420, 640));
  await page.waitForFunction(() => window.innerWidth === 420);
  await page.keyboard.press('Control+,');
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button', { name: /Refresh/ }).click();
  await expect(page.locator('.agent-card')).toHaveCount(6);
  expect(errors).toEqual([]);
  console.log('PASS: content-fitted 420px window, larger color-coded metrics, wide charts, daily costs, provider/day Stats, date validation, week navigation, filtering, keyboard tabs, themes, narrow/wide layouts, sandbox and preload.');
  console.log('Screenshots: .test-results/panel-{dark,light,narrow}.png and stats-{providers,days}.png');
} finally {
  await app?.close();
  await rm(home, { recursive: true, force: true });
}
